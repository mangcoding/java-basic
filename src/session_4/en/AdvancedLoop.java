package session_4.en;

public class AdvancedLoop {
    public static void main(String[] args) {
        for (int a=1; a<=3; a++) {
            for (int b=1; b<=5; b++) {
                System.out.print(a+" ");
            }
            System.out.println();
        }
    }
}

