package session_4.en;

public class NumberPattern {
    public static void main(String[] args) {
        for (int i=1; i<=19; i+=2) {
            System.out.print(i+" ");
        }
        System.out.println();
        for (int x=30; x>=0; x-=5) {
            System.out.print(x+" ");
        }
    }
}

