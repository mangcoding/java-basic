package session_4;
public class App {
    public static void main(String[] args) {
        // For digunakan untuk looping yang kita ketahui jumlahnya
        for (int i=0; i<10; i++) {
            System.out.print(i+" ");
        }
        System.out.println();
        System.out.println("=========================");
        // while digunakan untuk looping yang tidak kita ketahui jumlahnya
        int x = 0;
        while (x < 10) {
            System.out.print(x+" ");
            x++;
        }
    }
}
